"""Inspect the preserved UCI source files and write reproducible audit reports."""

from __future__ import annotations

import hashlib
import json
import zipfile
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
REPORTS = ROOT / "reports"

DATASETS = {
    "uci_350_default_of_credit_card_clients": {
        "dataset_id": 350,
        "page_url": "https://archive.ics.uci.edu/dataset/350/default+of+credit+card+clients",
        "archive_url": "https://archive.ics.uci.edu/static/public/350/default+of+credit+card+clients.zip",
        "archive": RAW / "uci_dataset_350_default_of_credit_card_clients.zip",
        "source": RAW / "uci_350_extracted" / "default of credit card clients.xls",
        "format": "xls",
        "target": "Y",
        "expected_target_values": {"0", "1"},
    },
    "uci_222_bank_marketing": {
        "dataset_id": 222,
        "page_url": "https://archive.ics.uci.edu/dataset/222/bank+marketing",
        "archive_url": "https://archive.ics.uci.edu/static/public/222/bank+marketing.zip",
        "archive": RAW / "uci_dataset_222_bank_marketing.zip",
        "source": RAW / "uci_222_extracted" / "bank" / "bank-full.csv",
        "format": "csv",
        "target": "y",
        "expected_target_values": {"no", "yes"},
    },
}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def archive_members(path: Path) -> list[str]:
    with zipfile.ZipFile(path) as archive:
        return archive.namelist()


def value_counts(series: pd.Series) -> dict[str, int]:
    counts = Counter(str(value) for value in series.dropna())
    return dict(sorted(counts.items()))


def inspect_dataset(config: dict) -> dict:
    archive = config["archive"]
    source = config["source"]
    if not archive.is_file():
        raise FileNotFoundError(f"Missing archive: {archive}")
    if not source.is_file():
        raise FileNotFoundError(f"Missing extracted source file: {source}")

    if config["format"] == "xls":
        sheets = pd.ExcelFile(source, engine="xlrd").sheet_names
        frame = pd.read_excel(source, sheet_name=0, engine="xlrd")
    else:
        sheets = []
        frame = pd.read_csv(source, sep=";")

    target = config["target"]
    if target not in frame.columns:
        raise ValueError(f"Target column {target!r} not found in {source}")
    raw_target_counts = value_counts(frame[target])
    expected_target_values = config["expected_target_values"]
    canonical_target = frame[target].map(str).isin(expected_target_values)

    return {
        "dataset_id": config["dataset_id"],
        "page_url": config["page_url"],
        "archive_url": config["archive_url"],
        "archive_file": archive.relative_to(ROOT).as_posix(),
        "archive_sha256": sha256(archive),
        "archive_size_bytes": archive.stat().st_size,
        "archive_members": archive_members(archive),
        "source_file": source.relative_to(ROOT).as_posix(),
        "source_sha256": sha256(source),
        "source_size_bytes": source.stat().st_size,
        "format": config["format"],
        "sheet_names": sheets,
        "rows": int(frame.shape[0]),
        "columns": int(frame.shape[1]),
        "column_names": [str(column) for column in frame.columns],
        "target_column": target,
        "target_value_counts_raw": raw_target_counts,
        "target_value_counts_expected_values": value_counts(
            frame.loc[canonical_target, target]
        ),
        "target_rows_outside_expected_values": int((~canonical_target).sum()),
        "missing_values_by_column": {
            str(column): int(count)
            for column, count in frame.isna().sum().items()
            if int(count) > 0
        },
    }


def render_markdown(audit: dict) -> str:
    lines = [
        "# Dataset audit",
        "",
        "> Generated by `python scripts/audit_datasets.py`. Facts below are read from",
        "> the preserved files in `data/raw/`; no model training or preprocessing is run.",
        "",
        f"Generated at (UTC): `{audit['generated_at_utc']}`",
        "",
    ]
    for name, item in audit["datasets"].items():
        lines.extend(
            [
                f"## {name}",
                "",
                f"- UCI dataset ID: `{item['dataset_id']}`",
                f"- Dataset page: {item['page_url']}",
                f"- Download URL: {item['archive_url']}",
                f"- Archive: `{item['archive_file']}` ({item['archive_size_bytes']} bytes)",
                f"- Archive SHA-256: `{item['archive_sha256']}`",
                f"- Archive members: `{', '.join(item['archive_members'])}`",
                f"- Inspected source: `{item['source_file']}` ({item['source_size_bytes']} bytes)",
                f"- Source SHA-256: `{item['source_sha256']}`",
                f"- Shape: `{item['rows']}` rows x `{item['columns']}` columns",
                f"- Target column: `{item['target_column']}`",
                f"- Target value counts as read: `{json.dumps(item['target_value_counts_raw'], sort_keys=True)}`",
                f"- Target counts restricted to expected values: `{json.dumps(item['target_value_counts_expected_values'], sort_keys=True)}`",
                f"- Rows outside expected target values: `{item['target_rows_outside_expected_values']}`",
                f"- Missing values (empty means none detected by pandas): `{json.dumps(item['missing_values_by_column'], sort_keys=True)}`",
                f"- Columns: `{', '.join(item['column_names'])}`",
                "",
            ]
        )
    return "\n".join(lines)


def main() -> None:
    audit = {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "datasets": {
            name: inspect_dataset(config) for name, config in DATASETS.items()
        },
    }
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / "dataset_audit.json").write_text(
        json.dumps(audit, indent=2) + "\n", encoding="utf-8"
    )
    (REPORTS / "dataset_audit.md").write_text(
        render_markdown(audit), encoding="utf-8"
    )
    print(render_markdown(audit))


if __name__ == "__main__":
    main()
